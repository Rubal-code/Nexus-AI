const MIN_SLIDES = 6;
const MAX_SLIDES = 10;

/** If the user asked for an explicit slide count ("5-slide deck"), honor it. */
function requestedSlideCount(prompt) {
  const m = /\b(\d{1,2})\s*(-\s*)?slides?\b/i.exec(prompt || "");
  if (!m) return null;
  const n = parseInt(m[1], 10);
  return Math.min(12, Math.max(3, n));
}

function slideCountRule(minSlides, maxSlides) {
  return minSlides === maxSlides
    ? `exactly ${minSlides} slides total. The user explicitly asked for ${minSlides} slides.`
    : `between ${minSlides} and ${maxSlides} slides total (never fewer, never more).`;
}

function buildSystemPrompt(minSlides, maxSlides) {
  return `You are Nexus AI's Presentation & Slide Architect.
Design a professional, visually-driven slide deck on the topic the user asks for.

Deck structure rules:
- The deck MUST contain ${slideCountRule(minSlides, maxSlides)}
- Slide 1: title slide -> give it a "subtitle" field (a one-line tagline) and no bullets.
- Slide 2: agenda -> 4-6 short bullets listing what the deck covers.
- Middle slides: 4-7 content slides that cover the topic IN DEPTH (definitions,
  how it works, benefits, challenges, real-world examples, data/trends, comparison,
  recommendations - as relevant to the topic).
- Final slide: conclusion / call-to-action.

Content quality rules:
- Every bullet must be a complete, information-rich sentence with concrete facts,
  examples, mechanisms or numbers - never vague labels like "Overview" or "Points".
- 3-6 bullets per content slide.
- Write a 1-2 sentence speaker note for EVERY slide.
- Stay strictly on the user's topic; every slide must be specific to it.
- Latin characters only; no emoji or special symbols.

Return ONLY a strict JSON array in this exact shape — no markdown, no commentary:

[
  {"title": "Slide title", "subtitle": "tagline (title slide only)", "bullets": ["bullet one", "bullet two"], "notes": "speaker note"}
]`;
}

