/** Normalize a raw slide object from the LLM into a safe, consistent shape. */
function normalizeSlide(raw) {
  const s = raw || {};
  return {
    title: String(s.title || "").replace(/\s+/g, " ").trim().slice(0, 70) || "Untitled Slide",
    subtitle: s.subtitle ? String(s.subtitle).replace(/\s+/g, " ").trim().slice(0, 120) : "",
    bullets: (Array.isArray(s.bullets) ? s.bullets : [])
      .map((b) => String(b).replace(/\s+/g, " ").trim())
      .filter(Boolean)
      .slice(0, 6),
    notes: String(s.notes || "").trim().slice(0, 500),
  };
}

export async function pptNode(state) {
  console.log(`[PPT Agent] Generating real .pptx for: "${state.prompt}"`);

  let artifact = null;
  let finalOutput = `### Presentation Generation\n\nBuilding a PowerPoint deck for **"${state.prompt}"**...`;

  try {
    const history = await getConversationHistory(state.conversationId);

    // Honor an explicit count from the user ("5-slide deck"), else default 6-10.
    const requested = requestedSlideCount(state.prompt);
    const minSlides = requested ?? MIN_SLIDES;
    const maxSlides = requested ?? MAX_SLIDES;

    const countInstruction = `Produce ${slideCountRule(minSlides, maxSlides)}`;

    let raw = await generateStructuredJson({
      systemPrompt: buildSystemPrompt(minSlides, maxSlides),
      prompt: `Create a presentation about: ${state.prompt}\n\n${countInstruction} Cover this specific topic in depth and follow all structure rules.`,
      history,
      temperature: 0.6,
      maxOutputTokens: 6000,
    });

    // Single resilience retry when the model does not return a usable array.
    if (!Array.isArray(raw) || !raw.some((s) => s && (s.title || s.bullets))) {
      console.warn("[PPT Agent] First pass returned invalid JSON; retrying once.");
      raw = await generateStructuredJson({
        systemPrompt:
          buildSystemPrompt(minSlides, maxSlides) +
          "\n\nThe previous attempt was invalid. Respond with ONLY the strict JSON array — no prose, no markdown.",
        prompt: `Create a presentation about: ${state.prompt}\n\n${countInstruction} Cover this specific topic in depth and follow all structure rules.`,
        history: [],
        temperature: 0.3,
        maxOutputTokens: 6000,
      });
    }

    // Some models wrap the array in an object: { "slides": [...] }
    if (raw && !Array.isArray(raw) && Array.isArray(raw.slides)) {
      raw = raw.slides;
    }

    let slides = Array.isArray(raw)
      ? raw
          .map(normalizeSlide)
          // Keep slides that have content; the title slide is valid with only
          // a subtitle and no bullets. Drop truly empty slides.
          .filter((s) => s.title && (s.bullets.length > 0 || s.subtitle))
      : [];

    if (slides.length === 0) {
      console.warn("[PPT Agent] LLM returned invalid deck, using fallback.");
      slides = FALLBACK_DECK.map((s) => ({
        ...normalizeSlide(s),
        title: s.title.replace("PPTX", state.prompt),
      }));
    }

    // Enforce the requested slide window: hard cap, then top up to the minimum.
    slides = slides.slice(0, maxSlides);
    if (slides.length < minSlides) {
      const pads = PAD_SLIDE_TEMPLATES(state.prompt).filter(
        (p) => !slides.some((s) => s.title.toLowerCase() === p.title.toLowerCase())
      );
      slides = slides.concat(pads.slice(0, minSlides - slides.length));
      console.log(`[PPT Agent] Deck topped up to ${slides.length} slides (min ${minSlides}).`);
    }

    const { buffer, slideCount } = await generatePptxBuffer(slides);

    const stored = await saveArtifact({
      data: buffer,
      filename: `nexus-deck-${Date.now()}.pptx`,
      mimeType:
        "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    });

    artifact = createArtifact({
      artifactType: "pptx",
      name: stored.name,
      mimeType: stored.mimeType,
      url: stored.url,
      previewType: "slides",
      metadata: {
        slideCount,
        slides,
        title: slides[0]?.title || state.prompt,
        generatedAt: new Date().toISOString(),
      },
    });

    finalOutput = `### Presentation Ready\n\nYour PowerPoint deck **"${slides[0]?.title || "Untitled"}"** has been generated with **${slideCount} slides**.\n\nPreview the slides above, or use the *Open* / *Download* actions to access the .pptx file.`;
    console.log(`[PPT Agent] Artifact stored: ${stored.name} (${slideCount} slides)`);
  } catch (error) {
    console.error(`[PPT Agent] Generation failed: ${error.message}`);
    finalOutput = `### Presentation Generation Failed\n\nI couldn't produce the PowerPoint deck right now.\n\n**Reason:** ${error.message || "Unknown error"}`;
  }

  if (state.conversationId) {
    await appendToMemory(state.conversationId, "user", state.prompt);
    await appendToMemory(state.conversationId, "assistant", finalOutput);
  }

  return {
    output: finalOutput,
    artifact,
    messages: [
      {
        role: "assistant",
        sender: "PPT Agent",
        content: finalOutput,
      },
    ],
  };
}